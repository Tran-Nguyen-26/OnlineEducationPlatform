package com.oep.coremodel.exception;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
    // --- General ---
    NOT_FOUND(HttpStatus.NOT_FOUND),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    // --- Course / Enrollment ---
    COURSE_NOT_OPEN(HttpStatus.CONFLICT),
    COURSE_FULL(HttpStatus.CONFLICT),
    INVALID_INVITE_CODE(HttpStatus.FORBIDDEN),
    ALREADY_ENROLLED(HttpStatus.CONFLICT),
    // --- Assessment ---
    QUIZ_LOCKED(HttpStatus.CONFLICT),
    ATTEMPT_LIMIT_REACHED(HttpStatus.CONFLICT),
    DEADLINE_PASSED(HttpStatus.CONFLICT),
    // --- Identity & Auth ---
    EMAIL_TAKEN(HttpStatus.CONFLICT),
    BAD_CREDENTIALS(HttpStatus.UNAUTHORIZED),
    ACCOUNT_DISABLED(HttpStatus.FORBIDDEN),
    INVALID_TOKEN(HttpStatus.UNAUTHORIZED),
    TOKEN_EXPIRED(HttpStatus.UNAUTHORIZED),
    MUST_CHANGE_PASSWORD(HttpStatus.FORBIDDEN),
    INSTRUCTOR_ROLE_REQUIRED(HttpStatus.FORBIDDEN),
    COURSE_NOT_EDITABLE(HttpStatus.CONFLICT),
    INVALID_COURSE_METADATA(HttpStatus.BAD_REQUEST),
    INVALID_COURSE_MODULE(HttpStatus.NOT_FOUND),
    INVALID_COURSE_LESSON(HttpStatus.NOT_FOUND),
    MODULE_NOT_EDITABLE(HttpStatus.FORBIDDEN),
    LESSON_NOT_EDITABLE(HttpStatus.FORBIDDEN),
    INVALID_MODULE_POSITION(HttpStatus.CONFLICT),
    MODULE_NOT_EMPTY(HttpStatus.CONFLICT),
    INVALID_LESSON_POSITION(HttpStatus.CONFLICT),
    LESSON_NOT_EMPTY(HttpStatus.CONFLICT),
    INVALID_MODULE_ORDER(HttpStatus.UNPROCESSABLE_ENTITY),
    INVALID_LESSON_ORDER(HttpStatus.UNPROCESSABLE_ENTITY),
    INVALID_CONTENT(HttpStatus.NOT_FOUND),
    INVALID_CONTENT_METADATA(HttpStatus.UNPROCESSABLE_ENTITY),
    CONTENT_POSITION_TAKEN(HttpStatus.CONFLICT),
    CONTENT_IN_USE(HttpStatus.CONFLICT),
    CONTENT_TYPE_NOT_SUPPORTED(HttpStatus.UNPROCESSABLE_ENTITY),
    INVALID_UPLOAD_STATE(HttpStatus.CONFLICT),
    UPLOAD_TOO_LARGE(HttpStatus.PAYLOAD_TOO_LARGE),
    UNSUPPORTED_MEDIA_TYPE(HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    UPLOAD_OBJECT_NOT_FOUND(HttpStatus.NOT_FOUND),
    UPLOAD_METADATA_MISMATCH(HttpStatus.UNPROCESSABLE_ENTITY),
    CONTENT_STORAGE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    INVALID_LIFECYCLE_TRANSITION(HttpStatus.CONFLICT),
    COURSE_NOT_READY(HttpStatus.CONFLICT),
    COURSE_OWNER_REQUIRED(HttpStatus.FORBIDDEN),
    CO_INSTRUCTOR_CANNOT_DELETE_COURSE(HttpStatus.FORBIDDEN),
    ADMIN_ROLE_REQUIRED(HttpStatus.FORBIDDEN),
    CANNOT_REMOVE_OWNER(HttpStatus.CONFLICT),
    COURSE_INSTRUCTOR_ALREADY_ASSIGNED(HttpStatus.CONFLICT);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) { this.status = status; }

    public HttpStatus status() { return status; }
}
