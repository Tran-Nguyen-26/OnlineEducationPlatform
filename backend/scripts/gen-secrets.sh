#!/usr/bin/env bash
# Generates local production-like secrets: backend/.env.prod and backend/secrets/jwt-private-pkcs8.pem.
# Both are git-ignored. Re-running keeps existing files unless you pass --force.
set -euo pipefail
cd "$(dirname "$0")/.."
FORCE="${1:-}"
mkdir -p secrets
rnd() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-24}"; }

if [[ ! -f secrets/jwt-private-pkcs8.pem || "$FORCE" == "--force" ]]; then
  openssl genrsa 2048 2>/dev/null | openssl pkcs8 -topk8 -nocrypt -out secrets/jwt-private-pkcs8.pem
  chmod 644 secrets/jwt-private-pkcs8.pem   # local compose bind mount, read by the non-root container user
  echo "JWT signing key written to secrets/jwt-private-pkcs8.pem"
fi

if [[ -f .env.prod && "$FORCE" != "--force" ]]; then
  echo ".env.prod already exists (use --force to regenerate)"; exit 0
fi
ADMIN_PW="Adm1n-$(rnd 14)"
cat > .env.prod <<ENV
# Generated by scripts/gen-secrets.sh — local production-like stack. NEVER commit.
COMPOSE_PROJECT_NAME=oep-prod
FRONTEND_PORT=8088
PUBLIC_ORIGIN=http://localhost:8088

DB_NAME=oep
DB_USER=oep
DB_PASSWORD=$(rnd 28)
REDIS_PASSWORD=$(rnd 28)
RABBIT_USER=oep
RABBIT_PASSWORD=$(rnd 28)

STORAGE_ACCESS_KEY=oepminio
STORAGE_SECRET_KEY=$(rnd 32)
STORAGE_BUCKET=oep-content
# What the BROWSER uses to reach object storage (presigned URLs). Real AWS S3: leave STORAGE_ENDPOINT / this empty.
STORAGE_PUBLIC_ORIGIN=http://localhost:9000

ADMIN_SEED_EMAIL=admin@oep.local
ADMIN_SEED_PASSWORD=${ADMIN_PW}
ENV
chmod 600 .env.prod
echo ".env.prod written. Initial admin login: admin@oep.local / ${ADMIN_PW}  (forced to change on first login)"
